#ifndef VCO_VITA_AUTHORITY_H
#define VCO_VITA_AUTHORITY_H
#include "../../execution/session.h"
#include "../foreground_probe.h"
#include "process_events.h"
#include <stddef.h>

#define VCO_VITA_AUTHORITY_LEASE_US UINT64_C(250000)
/* Single kernel worker owns every field/API. RPC must authenticate the real
 * Shell object, copy observations, and attach KERNEL receipt time/epoch/serial
 * before publishing to this worker. None of these metadata come from users.
 * Only one prepared authority may own the global process-event target watch. */
typedef struct {
    VcoForegroundSample sample;
    VcoIdentity identity; /* instance=0 while prepared; memory_bind assigns it */
    uint64_t received_us, serial, last_clock;
    uint32_t received_epoch, bound_epoch;
    void *process_class, *process_object;
    int (*get_title)(int32_t, char *, uint32_t);
    int cleanup_error;
    bool candidate, held, retired, poisoned, clock_seen;
} VcoVitaGameAuthority;

/* Initialize once before use. Never reinitialize an object with references or
 * a poisoned cleanup history. A clean unbind permits another prepare. */
void vco_vita_authority_init(VcoVitaGameAuthority *);
/* Exactly sizeof(VcoForegroundSample), fixed ABI/reserved/identity validation.
 * All failures revoke the prior write observation. A valid UNKNOWN also
 * revokes it and returns 0. Replayed serials and expired queued samples never
 * renew the lease. This API does not itself retain/release target objects. */
int vco_vita_authority_accept(VcoVitaGameAuthority *, const void *sample, size_t length,
                              uint64_t kernel_received_us, uint32_t kernel_received_epoch,
                              uint64_t kernel_serial);
/* Return a fresh candidate's target. Does not assign process instance or grant
 * writes. Outputs change only on success. Used to detect target changes before
 * cleaning old engine/patches/memory bindings. */
int vco_vita_authority_target(VcoVitaGameAuthority *, int32_t *pid, char title_id[10]);
/* Retain candidate process object after independent kernel Title ID check.
 * Only when !held; then bind VcoVitaMemory with authorize below. */
int vco_vita_authority_prepare(VcoVitaGameAuthority *);
/* VcoVitaAuthority-compatible. On first successful foreground=false callback,
 * latch the instance generated by VcoVitaMemory. Subsequent instances must
 * match. foreground requires a live receipt lease + epoch + same observation;
 * false allows cleanup of the same independently verified retained object
 * despite background/UNKNOWN/expiry. A callback-side terminal watch denies
 * both before the event queue is consumed; this alone is not retirement proof
 * or synchronization with already-running native operations.
 * Retired/replaced/poisoned denies both. */
int vco_vita_authority_authorize(void *, const VcoIdentity *, bool foreground);
/* Worker session observation; never invents ABSENT from ambiguous evidence. */
VcoObservation vco_vita_authority_observation(VcoVitaGameAuthority *);
/* Optional event evidence, fed only by the kernel event consumer. Any target
 * event revokes the sampled write observation. Terminal events newer than the
 * retained binding retire that binding; older events require object identity
 * verification and cannot claim a replacement instance exited. */
void vco_vita_authority_event(VcoVitaGameAuthority *, const VcoProcessEvent *);
/* Revoke writes on owner/channel failure, retaining ownership for cleanup. */
void vco_vita_authority_revoke(VcoVitaGameAuthority *);
/* After engine/patch cleanup and memory_unbind. Consume retained reference
 * once; failed release poisons permanently. Preserve latest sample/receipt so
 * a different candidate may be prepared without re-timestamping or replaying. */
int vco_vita_authority_unbind(VcoVitaGameAuthority *);
#endif
