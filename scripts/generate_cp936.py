#!/usr/bin/env python3
"""Generate the readonly decoder table from the pinned Unicode CP936 data."""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'vendor/unicode/CP936.TXT'
TARGET = ROOT / 'src/catalog/cp936_table.inc'
SOURCE_HASH = 'b86f601c575e9ab457380b6f7abef03c75499cc6075bdc8b4b27f3f2de74bf6a'


def render():
    raw = SOURCE.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SOURCE_HASH:
        raise ValueError('CP936 source differs from the reviewed Unicode mapping')
    table = [0] * (126 * 190)
    singles = {}
    assigned = 0
    for line in raw.decode('ascii').splitlines():
        fields = line.split('#', 1)[0].split()
        if len(fields) != 2:
            continue
        code, value = (int(field, 16) for field in fields)
        if code < 256:
            singles[code] = value
            continue
        lead, trail = code >> 8, code & 255
        if not (0x81 <= lead <= 0xfe and 0x40 <= trail <= 0xfe and trail != 0x7f):
            raise ValueError(f'Unexpected CP936 pair {code:04x}')
        # Backward in-place conversion requires every pair to retain or expand.
        if not (0x80 <= value <= 0xffff and not 0xd800 <= value <= 0xdfff):
            raise ValueError(f'Unexpected Unicode mapping {value:04x}')
        index = (lead - 0x81) * 190 + trail - 0x40 - (trail > 0x7f)
        if table[index]:
            raise ValueError(f'Duplicate CP936 pair {code:04x}')
        table[index] = value
        assigned += 1
    if singles != {**dict(enumerate(range(128))), 0x80: 0x20ac} or assigned != 21791:
        raise ValueError('Unexpected CP936 repertoire')
    lines = ['/* Generated by scripts/generate_cp936.py; do not edit.',
             ' * Unicode CP936 2.01 (2000-01-07), Unicode License V3.',
             f' * Source SHA256: {SOURCE_HASH}',
             ' * See vendor/unicode/LICENSE.txt and README.md. */',
             '/* clang-format off */',
             'static const uint16_t cp936_table[126u * 190u] = {']
    lines += ['    ' + ', '.join(f'0x{value:04x}' for value in table[i:i + 10]) + ','
              for i in range(0, len(table), 10)]
    lines += ['};', '/* clang-format on */', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != expected:
            raise SystemExit('CP936 decoder table is stale; run scripts/generate_cp936.py')
    else:
        TARGET.write_text(expected)


if __name__ == '__main__':
    main()
